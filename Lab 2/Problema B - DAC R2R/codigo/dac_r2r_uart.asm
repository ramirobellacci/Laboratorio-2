; PROBLEMA B - DAC R2R

.include "m328pdef.inc"

.equ BPS = 103

.def aux       = r16
.def aux2      = r17
.def dato      = r18
.def tecla     = r19
.def muestra   = r20
.def senal     = r21
.def velocidad = r22

.cseg
.org 0x0000
    rjmp INICIO

INICIO:
    ; inicializo stack pointer
    ldi aux, high(RAMEND)
    out SPH, aux
    ldi aux, low(RAMEND)
    out SPL, aux

    rcall PUERTOS
    rcall USART
    rcall TIMER1

    ldi muestra, 0
    ldi senal, 0          ; 0 = senal 13, 1 = senal 15
    ldi velocidad, 2
    rcall CAMBIAR_VEL

    rcall MENU

MAIN:
    rcall LEER_USART
    rcall ESPERAR_TIMER
    rcall BUSCAR_DATO
    rcall SACAR_DAC
    inc muestra
    rjmp MAIN

;--------------------
; CONFIGURACION
;---------------------
PUERTOS:
    ; D0 RX, D1 TX, D2-D7 salida DAC
    ldi aux, 0b11111100
    out DDRD, aux

    ; D8-D9 salida DAC
    ldi aux, 0b00000011
    out DDRB, aux

    ldi aux, 0
    out PORTD, aux
    out PORTB, aux
    ret

USART:
    ; 9600 baudios con clock de 16 MHz
    ldi aux, high(BPS)
    sts UBRR0H, aux
    ldi aux, low(BPS)
    sts UBRR0L, aux

    ldi aux, (1<<RXEN0) | (1<<TXEN0)
    sts UCSR0B, aux

    ldi aux, (1<<UCSZ01) | (1<<UCSZ00)
    sts UCSR0C, aux
    ret

TIMER1:
    ; Timer1 en CTC, sin interrupciones
    ldi aux, 0
    sts TCCR1A, aux

    ldi aux, (1<<WGM12) | (1<<CS10)
    sts TCCR1B, aux

    ldi aux, (1<<OCF1A)
    sts TIFR1, aux
    ret

;-----------
; USART
;------------
PUTC:
    lds aux2, UCSR0A
    sbrs aux2, UDRE0
    rjmp PUTC
    sts UDR0, aux
    ret

GETC:
    lds aux, UCSR0A
    sbrs aux, RXC0
    ret

    lds tecla, UDR0

    cpi tecla, '1'
    breq ELEGIR_13
    cpi tecla, '2'
    breq ELEGIR_15
    cpi tecla, '+'
    breq MAS_RAPIDO
    cpi tecla, '-'
    breq MAS_LENTO
    cpi tecla, 'm'
    breq MOSTRAR_MENU
    cpi tecla, 'M'
    breq MOSTRAR_MENU
    ret

LEER_USART:
    rcall GETC
    ret

ELEGIR_13:
    ldi senal, 0
    ldi muestra, 0
    ret

ELEGIR_15:
    ldi senal, 1
    ldi muestra, 0
    ret

MAS_RAPIDO:
    cpi velocidad, 4
    breq FIN_VEL1
    inc velocidad
    rcall CAMBIAR_VEL
FIN_VEL1:
    ret

MAS_LENTO:
    cpi velocidad, 0
    breq FIN_VEL2
    dec velocidad
    rcall CAMBIAR_VEL
FIN_VEL2:
    ret

MOSTRAR_MENU:
    rcall MENU
    ret

TEXTO:
    lpm aux, Z+
    cpi aux, 0
    breq FIN_TEXTO
    rcall PUTC
    rjmp TEXTO
FIN_TEXTO:
    ret

MENU:
    ldi ZL, low(2*TXT1)
    ldi ZH, high(2*TXT1)
    rcall TEXTO
    ldi ZL, low(2*TXT2)
    ldi ZH, high(2*TXT2)
    rcall TEXTO
    ldi ZL, low(2*TXT3)
    ldi ZH, high(2*TXT3)
    rcall TEXTO
    ldi ZL, low(2*TXT4)
    ldi ZH, high(2*TXT4)
    rcall TEXTO
    ldi ZL, low(2*TXT5)
    ldi ZH, high(2*TXT5)
    rcall TEXTO
    ldi ZL, low(2*TXT6)
    ldi ZH, high(2*TXT6)
    rcall TEXTO
    ret

;----------------
; TIMER Y DAC
;---------------------

ESPERAR_TIMER:
    lds aux, TIFR1
    sbrs aux, OCF1A
    rjmp ESPERAR_TIMER

    ldi aux, (1<<OCF1A)
    sts TIFR1, aux
    ret

CAMBIAR_VEL:
    cpi velocidad, 0
    breq VEL0
    cpi velocidad, 1
    breq VEL1
    cpi velocidad, 2
    breq VEL2
    cpi velocidad, 3
    breq VEL3
    rjmp VEL4

VEL0:
    ldi aux2, high(3999)
    ldi aux, low(3999)
    rjmp CARGAR_OCR

VEL1:
    ldi aux2, high(1999)
    ldi aux, low(1999)
    rjmp CARGAR_OCR

VEL2:
    ldi aux2, high(999)
    ldi aux, low(999)
    rjmp CARGAR_OCR

VEL3:
    ldi aux2, high(499)
    ldi aux, low(499)
    rjmp CARGAR_OCR

VEL4:
    ldi aux2, high(249)
    ldi aux, low(249)

CARGAR_OCR:
    sts OCR1AH, aux2
    sts OCR1AL, aux

    ldi aux, 0
    sts TCNT1H, aux
    sts TCNT1L, aux

    ldi aux, (1<<OCF1A)
    sts TIFR1, aux
    ret

BUSCAR_DATO:
    cpi senal, 0
    breq TABLA_13

TABLA_15:
    ldi ZL, low(2*SENAL15)
    ldi ZH, high(2*SENAL15)
    rjmp SUMAR_INDICE

TABLA_13:
    ldi ZL, low(2*SENAL13)
    ldi ZH, high(2*SENAL13)

SUMAR_INDICE:
    add ZL, muestra
    ldi aux, 0
    adc ZH, aux
    lpm dato, Z
    ret

SACAR_DAC:
    ; bits 0 a 5 salen por D2 a D7
    mov aux, dato
    andi aux, 0b00111111
    lsl aux
    lsl aux

    in aux2, PORTD
    andi aux2, 0b00000011
    or aux, aux2
    out PORTD, aux

    ; bits 6 y 7 salen por D8 y D9
    mov aux, dato
    lsr aux
    lsr aux
    lsr aux
    lsr aux
    lsr aux
    lsr aux

    in aux2, PORTB
    andi aux2, 0b11111100
    or aux, aux2
    out PORTB, aux
    ret

