; PROBLEMA B
; dac r-2r de 8 bits con uart
; atmega328p - arduino uno compatible - 16 mhz - 9600 baudios

.include "m328pdef.inc"

.equ UBRR_VAL = 103
.equ SPEED_MIN = 0
.equ SPEED_MAX = 4

.def temp = r16
.def temp2 = r17
.def dato = r18
.def tecla = r19
.def indice = r20
.def ocrl = r24
.def ocrh = r25

.dseg
modo:       .byte 1
muestra:    .byte 1
velocidad:  .byte 1

.cseg
.org 0x0000
    rjmp reset

; INICIO
reset:
    ldi temp, low(RAMEND)
    out SPL, temp
    ldi temp, high(RAMEND)
    out SPH, temp

    call puertos_init
    call uart_init
    call timer1_init

    ldi temp, 0
    sts modo, temp
    sts muestra, temp

    ldi temp, 2
    sts velocidad, temp
    call aplicar_velocidad

    call imprimir_menu

principal:
    call leer_uart
    call actualizar_dac
    rjmp principal

; CONFIGURACION
puertos_init:
    ; d0 rx, d1 tx, d2 a d7 salida dac
    ldi temp, 0b11111100
    out DDRD, temp

    ; d8 y d9 salida dac
    ldi temp, 0b00000011
    out DDRB, temp

    clr temp
    out PORTD, temp
    out PORTB, temp
    ret

uart_init:
    ldi temp, high(UBRR_VAL)
    sts UBRR0H, temp
    ldi temp, low(UBRR_VAL)
    sts UBRR0L, temp

    ldi temp, (1 << RXEN0) | (1 << TXEN0)
    sts UCSR0B, temp

    ldi temp, (1 << UCSZ01) | (1 << UCSZ00)
    sts UCSR0C, temp
    ret

timer1_init:
    clr temp
    sts TCCR1A, temp

    ldi temp, (1 << WGM12) | (1 << CS10)
    sts TCCR1B, temp

    ldi temp, (1 << OCF1A)
    sts TIFR1, temp
    ret

; UART
uart_tx:
    lds temp2, UCSR0A
    sbrs temp2, UDRE0
    rjmp uart_tx
    sts UDR0, temp
    ret

uart_texto:
    lpm temp, Z+
    cpi temp, 0
    breq uart_texto_fin
    call uart_tx
    rjmp uart_texto
uart_texto_fin:
    ret

leer_uart:
    lds temp, UCSR0A
    sbrs temp, RXC0
    ret

    lds tecla, UDR0

    cpi tecla, '1'
    breq comando_senal13
    cpi tecla, '2'
    breq comando_senal15
    cpi tecla, '+'
    breq comando_mas_rapido
    cpi tecla, '-'
    breq comando_mas_lento
    cpi tecla, 'm'
    breq comando_menu
    cpi tecla, 'M'
    breq comando_menu
    ret

comando_senal13:
    ldi temp, 0
    sts modo, temp
    sts muestra, temp
    ret

comando_senal15:
    ldi temp, 1
    sts modo, temp
    clr temp
    sts muestra, temp
    ret

comando_mas_rapido:
    lds temp, velocidad
    cpi temp, SPEED_MAX
    breq velocidad_fin
    inc temp
    sts velocidad, temp
    call aplicar_velocidad
velocidad_fin:
    ret

comando_mas_lento:
    lds temp, velocidad
    cpi temp, SPEED_MIN
    breq velocidad_fin2
    dec temp
    sts velocidad, temp
    call aplicar_velocidad
velocidad_fin2:
    ret

comando_menu:
    call imprimir_menu
    ret

; DAC
actualizar_dac:
    lds temp, TIFR1
    sbrs temp, OCF1A
    ret

    ldi temp, (1 << OCF1A)
    sts TIFR1, temp

    call cargar_muestra
    call sacar_dac

    lds indice, muestra
    inc indice
    sts muestra, indice
    ret

cargar_muestra:
    lds temp, modo
    cpi temp, 0
    breq cargar_senal13

    ldi ZL, low(2 * senal_15)
    ldi ZH, high(2 * senal_15)
    rjmp cargar_senal

cargar_senal13:
    ldi ZL, low(2 * senal_13)
    ldi ZH, high(2 * senal_13)

cargar_senal:
    lds indice, muestra
    add ZL, indice
    clr temp
    adc ZH, temp
    lpm dato, Z
    ret

sacar_dac:
    ; bits 0 a 5 en d2 a d7
    mov temp, dato
    andi temp, 0x3F
    lsl temp
    lsl temp

    in temp2, PORTD
    andi temp2, 0b00000011
    or temp, temp2
    out PORTD, temp

    ; bits 6 y 7 en d8 y d9
    mov temp, dato
    lsr temp
    lsr temp
    lsr temp
    lsr temp
    lsr temp
    lsr temp

    in temp2, PORTB
    andi temp2, 0b11111100
    or temp, temp2
    out PORTB, temp
    ret

aplicar_velocidad:
    lds temp, velocidad

    cpi temp, 0
    breq vel0
    cpi temp, 1
    breq vel1
    cpi temp, 2
    breq vel2
    cpi temp, 3
    breq vel3
    rjmp vel4

vel0:
    ldi ocrh, high(3999)
    ldi ocrl, low(3999)
    rjmp cargar_ocr

vel1:
    ldi ocrh, high(1999)
    ldi ocrl, low(1999)
    rjmp cargar_ocr

vel2:
    ldi ocrh, high(999)
    ldi ocrl, low(999)
    rjmp cargar_ocr

vel3:
    ldi ocrh, high(499)
    ldi ocrl, low(499)
    rjmp cargar_ocr

vel4:
    ldi ocrh, high(249)
    ldi ocrl, low(249)

cargar_ocr:
    sts OCR1AH, ocrh
    sts OCR1AL, ocrl

    clr temp
    sts TCNT1H, temp
    sts TCNT1L, temp

    ldi temp, (1 << OCF1A)
    sts TIFR1, temp
    ret

imprimir_menu:
    ldi ZL, low(2 * texto_1)
    ldi ZH, high(2 * texto_1)
    call uart_texto
    ldi ZL, low(2 * texto_2)
    ldi ZH, high(2 * texto_2)
    call uart_texto
    ldi ZL, low(2 * texto_3)
    ldi ZH, high(2 * texto_3)
    call uart_texto
    ldi ZL, low(2 * texto_4)
    ldi ZH, high(2 * texto_4)
    call uart_texto
    ldi ZL, low(2 * texto_5)
    ldi ZH, high(2 * texto_5)
    call uart_texto
    ldi ZL, low(2 * texto_6)
    ldi ZH, high(2 * texto_6)
    call uart_texto
    ret

